def main():
    assert len(GLYPHS) == COUNT and all(len(g) == CELL for g in GLYPHS)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = os.path.join(root, "src")

    # --- src/font8x8.bin : raw bytes for the Zig impl's @embedFile ----------
    blob = bytes(b for g in GLYPHS for b in g)
    assert len(blob) == COUNT * CELL == 768
    with open(os.path.join(src, "font8x8.bin"), "wb") as f:
        f.write(blob)

    # --- src/font8x8.h : the same bytes for the C impl ----------------------
    out = []
    out.append("/* GENERATED by tools/gen_font8x8.py - do not edit by hand.")
    out.append(" *")
    out.append(" * ZUIL built-in bitmap font: printable-ASCII page, public-domain 8x8 VGA")
    out.append(" * font (Marcel Sondaar / IBM via Daniel Hepper's font8x8). Public Domain,")
    out.append(" * matching ZUIL's Unlicense. The C impl #includes this directly so the gcc")
    out.append(" * no-Zig hedge needs no build step; the Zig impl @embedFile's the twin")
    out.append(" * src/font8x8.bin (identical 768 bytes). The generator is dev-only and")
    out.append(" * unshipped, so it -- not the runtime -- may use SDL3_ttf/FreeType later.")
    out.append(" *")
    out.append(" * Convention: 8 bytes/glyph, row-major top row first; bit b (LSB=0) is")
    out.append(" * pixel column b from the LEFT; 1 = ink. The last cell (U+007F) is the")
    out.append(" * fallback box drawn for any non-ASCII / out-of-range byte. */")
    out.append("#ifndef ZUIL_FONT8X8_H")
    out.append("#define ZUIL_FONT8X8_H")
    out.append("")
    out.append("#define ZUIL_FONT_FIRST 0x%02X" % FIRST)
    out.append("#define ZUIL_FONT_COUNT %d" % COUNT)
    out.append("#define ZUIL_FONT_CELL  %d" % CELL)
    out.append("")
    out.append("static const unsigned char zuil_font8x8[ZUIL_FONT_COUNT][ZUIL_FONT_CELL] = {")
    for cp, g in zip(range(FIRST, FIRST + COUNT), GLYPHS):
        hexed = ", ".join("0x%02x" % b for b in g)
        ch = repr(chr(cp)) if cp < 0x7F else "'box'"
        out.append("    { %s },  /* U+%04X %s */" % (hexed, cp, ch))
    out.append("};")
    out.append("")
    out.append("#endif /* ZUIL_FONT8X8_H */")
    with open(os.path.join(src, "font8x8.h"), "w") as f:
        f.write("\n".join(out) + "\n")

    print("wrote src/font8x8.bin (%d bytes) and src/font8x8.h" % len(blob))


if __name__ == "__main__":
    main()
